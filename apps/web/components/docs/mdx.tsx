import type { MDXComponents } from "mdx/types";
import type { ReactNode } from "react";

const cx = (...c: (string | false | undefined)[]) => c.filter(Boolean).join(" ");

/** Steps of a task: numbered, each with its expected result (the spec's writing rule). */
export function Steps({ children }: { children: ReactNode }) {
  return <ol className="docs-steps my-4 flex flex-col gap-3">{children}</ol>;
}

/** A span, not a <p>: MDX puts it inside the step's paragraph, and <p> in <p> is invalid HTML. */
export function Result({ children }: { children: ReactNode }) {
  return <span className="mt-1 block border-l-2 border-border pl-2 text-muted">→ {children}</span>;
}

export function Callout({ type = "info", children }: { type?: "info" | "warning"; children: ReactNode }) {
  return (
    <div className={cx("my-4 border bg-surface-2 px-3 py-2", type === "warning" ? "border-warning" : "border-border")}>
      {type === "warning" && <span className="text-warning">! </span>}
      {children}
    </div>
  );
}

export function Kbd({ children }: { children: ReactNode }) {
  return <kbd className="rounded-xs border border-border px-1 text-[12px] text-muted">{children}</kbd>;
}

/** Real screenshot, generated by scripts/docs-screenshots.mjs with the demo bench. */
export function Shot({ src, alt }: { src: string; alt: string }) {
  return (
    <figure className="my-4">
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={src} alt={alt} loading="lazy" className="w-full border border-border" />
      <figcaption className="mt-1 text-[12px] text-muted">{alt}</figcaption>
    </figure>
  );
}

export const mdxComponents: MDXComponents = {
  h2: ({ children, id }) => (
    <h2 id={id} className="mt-8 mb-2 scroll-mt-4 border-b border-border pb-1 text-[16px]">
      <a href={`#${id}`} className="no-underline hover:underline">
        {children}
      </a>
    </h2>
  ),
  h3: ({ children, id }) => (
    <h3 id={id} className="mt-6 mb-2 scroll-mt-4 text-[14px]">
      <a href={`#${id}`} className="no-underline hover:underline">
        {children}
      </a>
    </h3>
  ),
  p: ({ children }) => <p className="my-2 max-w-3xl">{children}</p>,
  a: ({ href, children }) => (
    <a href={href} className="text-accent underline">
      {children}
    </a>
  ),
  ul: ({ children }) => <ul className="my-2 ml-5 max-w-3xl list-disc">{children}</ul>,
  ol: ({ children }) => <ol className="my-2 ml-5 max-w-3xl list-decimal">{children}</ol>,
  li: ({ children }) => <li className="my-1">{children}</li>,
  code: ({ children }) => <code className="border border-border bg-surface-2 px-1 text-[12px]">{children}</code>,
  pre: ({ children }) => <pre className="docs-pre my-3 max-w-3xl overflow-x-auto border border-border bg-surface-2 p-3 text-[12px]">{children}</pre>,
  table: ({ children }) => (
    <div className="my-3 overflow-x-auto">
      <table className="w-full max-w-5xl border-collapse text-left">{children}</table>
    </div>
  ),
  th: ({ children }) => <th className="border-b border-border py-1 pr-3 text-[12px] font-normal text-muted">{children}</th>,
  td: ({ children }) => <td className="border-b border-border/50 py-1 pr-3 align-top">{children}</td>,
  strong: ({ children }) => <strong className="font-semibold text-fg">{children}</strong>,
  Steps,
  Result,
  Callout,
  Kbd,
  Shot,
};
