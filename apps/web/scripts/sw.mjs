// Writes out/sw.js: a service worker that precaches the whole static export,
// so the tool and its docs work offline after the first visit. Revisions are
// content hashes, so a new build replaces exactly what changed.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = new URL("../out/", import.meta.url).pathname;

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* files(p);
    else yield p;
  }
}

// Agent downloads (~19 MB each) are not precached: they are fetched on demand.
const skip = (path) => path.endsWith(".txt") || path === "sw.js" || path.endsWith(".map") || path.startsWith("downloads/");
const entries = [];
let version = createHash("sha256");
for (const f of files(OUT)) {
  const rel = relative(OUT, f).split(sep).join("/");
  if (skip(rel)) continue;
  const hash = createHash("sha256").update(readFileSync(f)).digest("hex").slice(0, 12);
  version.update(rel + hash);
  // Pages are requested as /pt/ (trailingSlash): cache them under that URL.
  const url = "/" + rel.replace(/(^|\/)index\.html$/, "$1");
  entries.push([url, hash]);
}
const cacheName = "modfield-" + version.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/sw.mjs. Do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(entries.map(([u]) => u))};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // One by one: a single failed file must not leave the tool without its offline copy.
      for (const url of PRECACHE) {
        try {
          await cache.add(new Request(url, { cache: "reload" }));
        } catch {}
      }
      await self.skipWaiting();
    }),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("modfield-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

// Offline, a cached page is served without the host's security headers, so a
// framing defence must be re-attached here: frame-ancestors (ignored in <meta>)
// and X-Frame-Options. Only for documents, and only when a body exists.
function harden(res) {
  if (!res || !res.headers.get("content-type")?.includes("text/html")) return res;
  const headers = new Headers(res.headers);
  headers.set("X-Frame-Options", "DENY");
  headers.set("Content-Security-Policy", "frame-ancestors 'none'");
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  // Only our own GETs; the agent (127.0.0.1:4780x) and everything else go straight to the network.
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/_next/static/")) {
    // Immutable, content-hashed: cache first.
    event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
    return;
  }
  // Pages and the rest: network first (fresh when online), cache when offline.
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(async () =>
        harden((await caches.match(req)) || (await caches.match(url.pathname.endsWith("/") ? url.pathname : url.pathname + "/")) || (await caches.match("/404.html"))),
      ),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw: ${entries.length} files precached as ${cacheName}`);
