export const DICTS: Record<Lang, Dict> = { pt: { ...pt, ...pt2, ...pt3 }, en: { ...en, ...en2, ...en3 }, de: { ...de, ...de2, ...de3 } };

export const LANG_NAMES: Record<Lang, string> = { pt: "Português", en: "English", de: "Deutsch" };

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  const s = DICTS[lang][key];
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => String(params[k] ?? m)) : s;
}

/** Picks the UI language from the browser preferences. */
export function detectLang(languages: readonly string[]): Lang {
  for (const l of languages) {
    const short = l.slice(0, 2).toLowerCase();
    if (isLang(short)) return short;
  }
  return "pt";
}
